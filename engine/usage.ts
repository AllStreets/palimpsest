import { createHash } from 'node:crypto';
import { chmodSync, copyFileSync, existsSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join, resolve } from 'node:path';

import type { UsageReading, UsageWindow } from '../shared/types.js';
import { defaultHome, home, paths } from './home.js';
import { record } from './ledger.js';
import { isSampleHome, sampleClaudeSettingsPath } from './sample.js';
import { getSettings, patchSettings } from './settings.js';

const FIVE_HOURS_MS = 5 * 60 * 60 * 1000;

interface StatusLineValue {
  type?: string;
  command?: string;
  [key: string]: unknown;
}

interface RawWindow {
  used_percentage: number;
  resets_at: number;
}

interface RawRateLimits {
  five_hour?: RawWindow;
  seven_day?: RawWindow;
}

interface RawRecord {
  at: number;
  rate_limits?: RawRateLimits;
}

/** Why the hook will not touch any Claude settings file from this engine, when it will not. */
export const NO_CLAUDE_SETTINGS =
  'This engine keeps its data outside the default folder, so it will not change your Claude settings. Set PALIMPSEST_CLAUDE_SETTINGS to the settings file it should use.';

/**
 * The Claude Code settings file the usage hook may change, or null when none
 * safely can be: a sample home's own stand-in file, else the file
 * PALIMPSEST_CLAUDE_SETTINGS names, else the real ~/.claude/settings.json,
 * but only for an engine on the default data home. An engine on any other
 * home (a test, a second engine) never reaches the real file by default.
 */
export function claudeSettingsTarget(env: NodeJS.ProcessEnv = process.env): string | null {
  if (isSampleHome()) return sampleClaudeSettingsPath();
  if (env.PALIMPSEST_CLAUDE_SETTINGS) return resolve(env.PALIMPSEST_CLAUDE_SETTINGS);
  if (resolve(home()) !== resolve(defaultHome())) return null;
  return join(homedir(), '.claude', 'settings.json');
}

/** Shell-quotes `s` for embedding as a single-quoted POSIX sh literal. */
function shQuote(s: string): string {
  return `'${s.replace(/'/g, "'\\''")}'`;
}

/** Absolute path to the generated hook script, under paths().usage. */
function hookScriptPath(): string {
  return join(paths().usage, 'statusline.sh');
}

/** The exact statusLine.command value installHook writes; used to detect our own hook. */
function hookCommand(): string {
  return `sh ${shQuote(hookScriptPath())}`;
}

/** Where installHook keeps the SHA-256 of the settings file exactly as it wrote it. */
function writtenHashPath(): string {
  return join(paths().usage, 'settings.json.written.sha256');
}

function sha256(text: string): string {
  return createHash('sha256').update(text).digest('hex');
}

/** True when the settings text is still exactly what installHook last wrote: nothing else has changed it since. */
function unchangedSinceInstall(raw: string): boolean {
  const hashPath = writtenHashPath();
  return existsSync(hashPath) && readFileSync(hashPath, 'utf8').trim() === sha256(raw);
}

/** Reads `settings.statusLine`, whatever shape it is, or undefined if absent. */
function readStatusLine(settings: unknown): StatusLineValue | undefined {
  if (settings && typeof settings === 'object' && 'statusLine' in settings) {
    return (settings as { statusLine?: StatusLineValue }).statusLine;
  }
  return undefined;
}

/** The previous statusline's command string, when it was a 'command' type; null otherwise. */
function previousCommandFrom(statusLine: StatusLineValue | null | undefined): string | null {
  if (statusLine && statusLine.type === 'command' && typeof statusLine.command === 'string') {
    return statusLine.command;
  }
  return null;
}

/**
 * A POSIX sh script: reads Claude Code's statusline JSON from stdin, and
 * when `.rate_limits` is present, records it to `<usage>/latest.json`
 * (always overwritten) and, only when it changed since the last run, appends
 * it to `<usage>/readings.jsonl`. It then pipes the same stdin into
 * `previousCommand` (when given) and prints its output, else prints nothing.
 * Looks for `jq` on PATH, then /opt/homebrew/bin/jq, then /usr/local/bin/jq;
 * with none found, or on any jq failure, it records nothing but still
 * chains. Always exits 0.
 */
export function hookScript(previousCommand: string | null): string {
  const usageDir = paths().usage;
  const latestPath = join(usageDir, 'latest.json');
  const readingsPath = join(usageDir, 'readings.jsonl');

  const lines = [
    '#!/bin/sh',
    '# Generated by Palimpsest. Do not edit by hand; re-run installHook instead.',
    'set -u',
    '',
    'TMP=$(mktemp "${TMPDIR:-/tmp}/palimpsest-statusline.XXXXXX" 2>/dev/null) || TMP=""',
    'if [ -n "$TMP" ]; then',
    '  trap \'rm -f "$TMP"\' EXIT',
    '  cat > "$TMP"',
    'fi',
    '',
    'if command -v jq >/dev/null 2>&1; then',
    '  JQ=jq',
    'elif [ -x /opt/homebrew/bin/jq ]; then',
    '  JQ=/opt/homebrew/bin/jq',
    'elif [ -x /usr/local/bin/jq ]; then',
    '  JQ=/usr/local/bin/jq',
    'else',
    '  JQ=',
    'fi',
    '',
    'if [ -n "$JQ" ] && [ -n "$TMP" ]; then',
    `  LATEST=${shQuote(latestPath)}`,
    `  READINGS=${shQuote(readingsPath)}`,
    '  RATE_LIMITS=$("$JQ" -c \'.rate_limits // empty\' "$TMP" 2>/dev/null)',
    '  if [ -n "$RATE_LIMITS" ] && [ "$RATE_LIMITS" != "null" ]; then',
    '    AT=$(date +%s)',
    '    RECORD=$("$JQ" -cn --argjson at "$AT" --argjson rate_limits "$RATE_LIMITS" \'{at: $at, rate_limits: $rate_limits}\' 2>/dev/null)',
    '    if [ -n "$RECORD" ]; then',
    '      PREV_RL=""',
    '      if [ -f "$LATEST" ]; then',
    '        PREV_RL=$("$JQ" -c \'.rate_limits // empty\' "$LATEST" 2>/dev/null)',
    '      fi',
    '      printf \'%s\\n\' "$RECORD" > "$LATEST" 2>/dev/null',
    '      if [ "$RATE_LIMITS" != "$PREV_RL" ]; then',
    '        printf \'%s\\n\' "$RECORD" >> "$READINGS" 2>/dev/null',
    '      fi',
    '    fi',
    '  fi',
    'fi',
    '',
    `PREV_CMD=${shQuote(previousCommand ?? '')}`,
    'if [ -n "$PREV_CMD" ] && [ -n "$TMP" ]; then',
    '  cat "$TMP" | sh -c "$PREV_CMD"',
    'fi',
    '',
    'exit 0',
    '',
  ];

  return lines.join('\n');
}

/**
 * Installs the usage hook into the real Claude Code settings file (or
 * `claudeSettingsPath`, for tests). Idempotent: if the file's current
 * `statusLine` already points at our hook script, this only rewrites the
 * script (so it picks up any path changes) and re-affirms `hookInstalled`
 * — it does not take a new backup or touch `Settings.previousStatusLine`,
 * since a fresh backup at that point would just capture our own installed
 * state and overwrite the real original. Otherwise it backs the file up
 * byte for byte to `<usage>/settings.json.bak`, saves the current
 * `statusLine` value as `Settings.previousStatusLine`, and writes a script
 * chained to it. Either way it points `statusLine` at the script (keeping
 * the previous statusline's other keys, such as padding), records the
 * SHA-256 of the file as written so uninstall can tell whether anything has
 * changed it since, and records `usage.hook.installed`.
 */
export function installHook(claudeSettingsPath: string = join(homedir(), '.claude', 'settings.json')): void {
  const usageDir = paths().usage;
  const scriptPath = hookScriptPath();
  const ourCommand = hookCommand();
  const backupPath = join(usageDir, 'settings.json.bak');

  const raw = existsSync(claudeSettingsPath) ? readFileSync(claudeSettingsPath, 'utf8') : '{}';
  const parsed: unknown = JSON.parse(raw.trim() === '' ? '{}' : raw);
  const currentStatusLine = readStatusLine(parsed);
  const alreadyOurs = currentStatusLine?.type === 'command' && currentStatusLine.command === ourCommand;
  // A reinstall over a file someone has changed since the first install must not
  // vouch for those changes as ours: the backup would then undo them on uninstall.
  const ownWrite = !alreadyOurs || unchangedSinceInstall(raw);

  let previousCommand: string | null;

  if (alreadyOurs) {
    previousCommand = previousCommandFrom(getSettings().previousStatusLine as StatusLineValue | null);
  } else {
    if (existsSync(claudeSettingsPath)) {
      copyFileSync(claudeSettingsPath, backupPath);
    } else {
      writeFileSync(backupPath, raw);
    }
    patchSettings({ previousStatusLine: currentStatusLine ?? null });
    previousCommand = previousCommandFrom(currentStatusLine);
  }

  writeFileSync(scriptPath, hookScript(previousCommand));
  chmodSync(scriptPath, 0o755);

  const base = typeof parsed === 'object' && parsed !== null ? (parsed as Record<string, unknown>) : {};
  // Keep whatever else the statusline had (padding, say); only what runs changes.
  const kept = currentStatusLine && typeof currentStatusLine === 'object' ? currentStatusLine : {};
  const updated = { ...base, statusLine: { ...kept, type: 'command', command: ourCommand } };
  const written = JSON.stringify(updated, null, 2);
  writeFileSync(claudeSettingsPath, written);
  if (ownWrite) writeFileSync(writtenHashPath(), `${sha256(written)}\n`);
  else rmSync(writtenHashPath(), { force: true });

  patchSettings({ hookInstalled: true });
  record('usage.hook.installed', { claudeSettingsPath });
}

/**
 * Uninstalls the usage hook. When the settings file is still exactly what
 * installHook wrote (its hash matches), restores the backup byte for byte.
 * Otherwise something has changed the file since install, so only
 * `statusLine` goes back to the saved previous value (removed when there was
 * none) and every other change made since install is kept.
 *
 * A no-op (the file is never read or written) unless `Settings.hookInstalled`
 * is true or the file's current `statusLine` already points at our hook:
 * with neither true, there is nothing of ours to remove, and touching the
 * file would risk overwriting an unrelated custom `statusLine` with a stale
 * `previousStatusLine` left over from some earlier, unrelated install.
 */
export function uninstallHook(claudeSettingsPath: string = join(homedir(), '.claude', 'settings.json')): void {
  const usageDir = paths().usage;
  const backupPath = join(usageDir, 'settings.json.bak');
  const ourCommand = hookCommand();

  const raw = existsSync(claudeSettingsPath) ? readFileSync(claudeSettingsPath, 'utf8') : '{}';
  const parsed: unknown = JSON.parse(raw.trim() === '' ? '{}' : raw);
  const currentStatusLine = readStatusLine(parsed);
  const stillOurs = currentStatusLine?.type === 'command' && currentStatusLine.command === ourCommand;

  if (!getSettings().hookInstalled && !stillOurs) {
    return;
  }

  if (stillOurs && existsSync(backupPath) && unchangedSinceInstall(raw)) {
    copyFileSync(backupPath, claudeSettingsPath);
  } else {
    const previous = getSettings().previousStatusLine as StatusLineValue | null;
    const base = typeof parsed === 'object' && parsed !== null ? (parsed as Record<string, unknown>) : {};
    const updated: Record<string, unknown> = { ...base };
    if (previous === null || previous === undefined) {
      delete updated.statusLine;
    } else {
      updated.statusLine = previous;
    }
    writeFileSync(claudeSettingsPath, JSON.stringify(updated, null, 2));
  }

  rmSync(writtenHashPath(), { force: true });
  patchSettings({ hookInstalled: false });
}

function mapWindow(w: RawWindow | undefined): UsageWindow | null {
  if (!w) return null;
  return { usedPercentage: w.used_percentage, resetsAt: w.resets_at };
}

function mapRecord(raw: RawRecord): UsageReading {
  return {
    at: raw.at * 1000,
    fiveHour: mapWindow(raw.rate_limits?.five_hour),
    sevenDay: mapWindow(raw.rate_limits?.seven_day),
  };
}

/** The last recorded usage reading: `<usage>/latest.json`, falling back to the last line of readings.jsonl. */
export function latestReading(): UsageReading | null {
  const usageDir = paths().usage;
  const latestPath = join(usageDir, 'latest.json');

  if (existsSync(latestPath)) {
    const text = readFileSync(latestPath, 'utf8').trim();
    if (text) {
      try {
        return mapRecord(JSON.parse(text) as RawRecord);
      } catch {
        // Corrupt latest.json: fall through to readings.jsonl.
      }
    }
  }

  const readingsPath = join(usageDir, 'readings.jsonl');
  if (!existsSync(readingsPath)) return null;

  const lines = readFileSync(readingsPath, 'utf8')
    .split('\n')
    .filter((l) => l.trim() !== '');
  if (lines.length === 0) return null;

  try {
    return mapRecord(JSON.parse(lines[lines.length - 1]) as RawRecord);
  } catch {
    return null;
  }
}

/** True when `r` is older than 5 hours relative to `now`. */
export function isStale(r: UsageReading, now: number = Date.now()): boolean {
  return now - r.at > FIVE_HOURS_MS;
}

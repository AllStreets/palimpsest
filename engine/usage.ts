/** Why the hook will not touch any Claude settings file from this engine, when it will not. */
export const NO_CLAUDE_SETTINGS =
  'This engine keeps its data outside the default folder, so it will not change your Claude settings. Set PALIMPSEST_CLAUDE_SETTINGS to the settings file it should use.';

/**
 * The Claude Code settings file the usage hook may change, or null when none
 * safely can be: a sample home's own stand-in file, else the file
 * PALIMPSEST_CLAUDE_SETTINGS names, else the real ~/.claude/settings.json,
 * but only for an engine on the default data home. An engine on any other
 * home (a test, a second engine) never reaches the real file by default.
 */
export function claudeSettingsTarget(env: NodeJS.ProcessEnv = process.env): string | null {
  if (isSampleHome()) return sampleClaudeSettingsPath();
  if (env.PALIMPSEST_CLAUDE_SETTINGS) return resolve(env.PALIMPSEST_CLAUDE_SETTINGS);
  if (resolve(home()) !== resolve(defaultHome())) return null;
  return join(homedir(), '.claude', 'settings.json');
}

/** Shell-quotes `s` for embedding as a single-quoted POSIX sh literal. */
function shQuote(s: string): string {
  return `'${s.replace(/'/g, "'\\''")}'`;
}

/** Absolute path to the generated hook script, under paths().usage. */
function hookScriptPath(): string {
  return join(paths().usage, 'statusline.sh');
}

/** The exact statusLine.command value installHook writes; used to detect our own hook. */
function hookCommand(): string {
  return `sh ${shQuote(hookScriptPath())}`;
}

/** Where installHook keeps the SHA-256 of the settings file exactly as it wrote it. */
function writtenHashPath(): string {
  return join(paths().usage, 'settings.json.written.sha256');
}

function sha256(text: string): string {
  return createHash('sha256').update(text).digest('hex');
}

/** True when the settings text is still exactly what installHook last wrote: nothing else has changed it since. */
function unchangedSinceInstall(raw: string): boolean {
  const hashPath = writtenHashPath();
  return existsSync(hashPath) && readFileSync(hashPath, 'utf8').trim() === sha256(raw);
}

/** Reads `settings.statusLine`, whatever shape it is, or undefined if absent. */
function readStatusLine(settings: unknown): StatusLineValue | undefined {
  if (settings && typeof settings === 'object' && 'statusLine' in settings) {
    return (settings as { statusLine?: StatusLineValue }).statusLine;
  }
  return undefined;
}

/** The previous statusline's command string, when it was a 'command' type; null otherwise. */
function previousCommandFrom(statusLine: StatusLineValue | null | undefined): string | null {
  if (statusLine && statusLine.type === 'command' && typeof statusLine.command === 'string') {
    return statusLine.command;
  }
  return null;
}

/**
 * A POSIX sh script: reads Claude Code's statusline JSON from stdin, and
 * when `.rate_limits` is present, records it to `<usage>/latest.json`
 * (always overwritten) and, only when it changed since the last run, appends
 * it to `<usage>/readings.jsonl`. It then pipes the same stdin into
 * `previousCommand` (when given) and prints its output, else prints nothing.
 * Looks for `jq` on PATH, then /opt/homebrew/bin/jq, then /usr/local/bin/jq;
 * with none found, or on any jq failure, it records nothing but still
 * chains. Always exits 0.
 */
export function hookScript(previousCommand: string | null): string {
  const usageDir = paths().usage;
  const latestPath = join(usageDir, 'latest.json');
  const readingsPath = join(usageDir, 'readings.jsonl');

  const lines = [
    '#!/bin/sh',
    '# Generated by Palimpsest. Do not edit by hand; re-run installHook instead.',
    'set -u',
    '',
    'TMP=$(mktemp "${TMPDIR:-/tmp}/palimpsest-statusline.XXXXXX" 2>/dev/null) || TMP=""',
    'if [ -n "$TMP" ]; then',
    '  trap \'rm -f "$TMP"\' EXIT',
    '  cat > "$TMP"',
    'fi',
    '',
    'if command -v jq >/dev/null 2>&1; then',
    '  JQ=jq',
    'elif [ -x /opt/homebrew/bin/jq ]; then',
    '  JQ=/opt/homebrew/bin/jq',
    'elif [ -x /usr/local/bin/jq ]; then',
    '  JQ=/usr/local/bin/jq',
    'else',
    '  JQ=',
    'fi',
    '',
    'if [ -n "$JQ" ] && [ -n "$TMP" ]; then',
    `  LATEST=${shQuote(latestPath)}`,
    `  READINGS=${shQuote(readingsPath)}`,
    '  RATE_LIMITS=$("$JQ" -c \'.rate_limits // empty\' "$TMP" 2>/dev/null)',
    '  if [ -n "$RATE_LIMITS" ] && [ "$RATE_LIMITS" != "null" ]; then',
    '    AT=$(date +%s)',
    '    RECORD=$("$JQ" -cn --argjson at "$AT" --argjson rate_limits "$RATE_LIMITS" \'{at: $at, rate_limits: $rate_limits}\' 2>/dev/null)',
    '    if [ -n "$RECORD" ]; then',
    '      PREV_RL=""',
    '      if [ -f "$LATEST" ]; then',
    '        PREV_RL=$("$JQ" -c \'.rate_limits // empty\' "$LATEST" 2>/dev/null)',
    '      fi',
    '      printf \'%s\\n\' "$RECORD" > "$LATEST" 2>/dev/null',
    '      if [ "$RATE_LIMITS" != "$PREV_RL" ]; then',
    '        printf \'%s\\n\' "$RECORD" >> "$READINGS" 2>/dev/null',
    '      fi',
    '    fi',
    '  fi',
    'fi',
    '',
    `PREV_CMD=${shQuote(previousCommand ?? '')}`,
    'if [ -n "$PREV_CMD" ] && [ -n "$TMP" ]; then',
    '  cat "$TMP" | sh -c "$PREV_CMD"',
    'fi',
    '',
    'exit 0',
    '',
  ];

  return lines.join('\n');
}

/**
 * Installs the usage hook into the real Claude Code settings file (or
 * `claudeSettingsPath`, for tests). Idempotent: if the file's current
 * `statusLine` already points at our hook script, this only rewrites the
 * script (so it picks up any path changes) and re-affirms `hookInstalled`
 * — it does not take a new backup or touch `Settings.previousStatusLine`,
 * since a fresh backup at that point would just capture our own installed
 * state and overwrite the real original. Otherwise it backs the file up
 * byte for byte to `<usage>/settings.json.bak`, saves the current
 * `statusLine` value as `Settings.previousStatusLine`, and writes a script
 * chained to it. Either way it points `statusLine` at the script (keeping
 * the previous statusline's other keys, such as padding), records the
 * SHA-256 of the file as written so uninstall can tell whether anything has
 * changed it since, and records `usage.hook.installed`.
 */
export function installHook(claudeSettingsPath: string = join(homedir(), '.claude', 'settings.json')): void {
  const usageDir = paths().usage;
  const scriptPath = hookScriptPath();
  const ourCommand = hookCommand();
  const backupPath = join(usageDir, 'settings.json.bak');

  const raw = existsSync(claudeSettingsPath) ? readFileSync(claudeSettingsPath, 'utf8') : '{}';
  const parsed: unknown = JSON.parse(raw.trim() === '' ? '{}' : raw);
  const currentStatusLine = readStatusLine(parsed);
  const alreadyOurs = currentStatusLine?.type === 'command' && currentStatusLine.command === ourCommand;
  // A reinstall over a file someone has changed since the first install must not
  // vouch for those changes as ours: the backup would then undo them on uninstall.
  const ownWrite = !alreadyOurs || unchangedSinceInstall(raw);

  let previousCommand: string | null;

  if (alreadyOurs) {
    previousCommand = previousCommandFrom(getSettings().previousStatusLine as StatusLineValue | null);
  } else {
    if (existsSync(claudeSettingsPath)) {
      copyFileSync(claudeSettingsPath, backupPath);
    } else {
      writeFileSync(backupPath, raw);
    }
    patchSettings({ previousStatusLine: currentStatusLine ?? null });
    previousCommand = previousCommandFrom(currentStatusLine);
  }

  writeFileSync(scriptPath, hookScript(previousCommand));
  chmodSync(scriptPath, 0o755);

  const base = typeof parsed === 'object' && parsed !== null ? (parsed as Record<string, unknown>) : {};
  // Keep whatever else the statusline had (padding, say); only what runs changes.
  const kept = currentStatusLine && typeof currentStatusLine === 'object' ? currentStatusLine : {};
  const updated = { ...base, statusLine: { ...kept, type: 'command', command: ourCommand } };
  const written = JSON.stringify(updated, null, 2);
  writeFileSync(claudeSettingsPath, written);
  if (ownWrite) writeFileSync(writtenHashPath(), `${sha256(written)}\n`);
  else rmSync(writtenHashPath(), { force: true });

  patchSettings({ hookInstalled: true });
  record('usage.hook.installed', { claudeSettingsPath });
}

/**
 * Uninstalls the usage hook. When the settings file is still exactly what
 * installHook wrote (its hash matches), restores the backup byte for byte.
 * Otherwise something has changed the file since install, so only
 * `statusLine` goes back to the saved previous value (removed when there was
 * none) and every other change made since install is kept.
 *
 * A no-op (the file is never read or written) unless `Settings.hookInstalled`
 * is true or the file's current `statusLine` already points at our hook:
 * with neither true, there is nothing of ours to remove, and touching the
 * file would risk overwriting an unrelated custom `statusLine` with a stale
 * `previousStatusLine` left over from some earlier, unrelated install.
 */
export function uninstallHook(claudeSettingsPath: string = join(homedir(), '.claude', 'settings.json')): void {
  const usageDir = paths().usage;
  const backupPath = join(usageDir, 'settings.json.bak');
  const ourCommand = hookCommand();

  const raw = existsSync(claudeSettingsPath) ? readFileSync(claudeSettingsPath, 'utf8') : '{}';
  const parsed: unknown = JSON.parse(raw.trim() === '' ? '{}' : raw);
  const currentStatusLine = readStatusLine(parsed);
  const stillOurs = currentStatusLine?.type === 'command' && currentStatusLine.command === ourCommand;

  if (!getSettings().hookInstalled && !stillOurs) {
    return;
  }

  if (stillOurs && existsSync(backupPath) && unchangedSinceInstall(raw)) {
    copyFileSync(backupPath, claudeSettingsPath);
  } else {
    const previous = getSettings().previousStatusLine as StatusLineValue | null;
    const base = typeof parsed === 'object' && parsed !== null ? (parsed as Record<string, unknown>) : {};
    const updated: Record<string, unknown> = { ...base };
    if (previous === null || previous === undefined) {
      delete updated.statusLine;
    } else {
      updated.statusLine = previous;
    }
    writeFileSync(claudeSettingsPath, JSON.stringify(updated, null, 2));
  }

  rmSync(writtenHashPath(), { force: true });
  patchSettings({ hookInstalled: false });
}

function mapWindow(w: RawWindow | undefined): UsageWindow | null {
  if (!w) return null;
  return { usedPercentage: w.used_percentage, resetsAt: w.resets_at };
}

function mapRecord(raw: RawRecord): UsageReading {
  return {
    at: raw.at * 1000,
    fiveHour: mapWindow(raw.rate_limits?.five_hour),
    sevenDay: mapWindow(raw.rate_limits?.seven_day),
  };
}

/** The last recorded usage reading: `<usage>/latest.json`, falling back to the last line of readings.jsonl. */
export function latestReading(): UsageReading | null {
  const usageDir = paths().usage;
  const latestPath = join(usageDir, 'latest.json');

  if (existsSync(latestPath)) {
    const text = readFileSync(latestPath, 'utf8').trim();
    if (text) {
      try {
        return mapRecord(JSON.parse(text) as RawRecord);
      } catch {
        // Corrupt latest.json: fall through to readings.jsonl.
      }
    }
  }

  const readingsPath = join(usageDir, 'readings.jsonl');
  if (!existsSync(readingsPath)) return null;

  const lines = readFileSync(readingsPath, 'utf8')
    .split('\n')
    .filter((l) => l.trim() !== '');
  if (lines.length === 0) return null;

  try {
    return mapRecord(JSON.parse(lines[lines.length - 1]) as RawRecord);
  } catch {
    return null;
  }
}

/** True when `r` is older than 5 hours relative to `now`. */
export function isStale(r: UsageReading, now: number = Date.now()): boolean {
  return now - r.at > FIVE_HOURS_MS;
}

// ---------------------------------------------------------------- transcripts and calibration (ruling 2)

const INTERACTIVE_MS = 10 * 60 * 1000;
/** Weekly percentage points per percent of the five-hour window, until the readings measure it. Deliberately high, so an unmeasured week is overcounted rather than undercounted. */
export const DEFAULT_WEEK_PER_WINDOW_PCT = 0.25;
/** Five-hour percentage points the ratio needs before the measured one replaces the assumed one. */
const WEEK_RATIO_MIN_PCT = 5;

/** His real transcripts folder. */
function realProjectsRoot(): string {
  return join(homedir(), '.claude', 'projects');
}

/** The real path of `p`, or `p` resolved when it does not exist. */
function realOrResolved(p: string): string {
  const abs = resolve(p);
  try {
    return realpathSync.native(abs);
  } catch {
    return abs;
  }
}

/**
 * Refuses a transcripts folder outside ~/.claude/projects (after resolving
 * symlinks) unless PALIMPSEST_TEST_PROJECTS=1, which only tests set: the
 * scan never reads anything but his session transcripts.
 */
function checkedProjectsDir(dir: string): string {
  const abs = resolve(dir);
  if (process.env.PALIMPSEST_TEST_PROJECTS === '1') return abs;
  const root = realOrResolved(realProjectsRoot());
  const rel = relative(root, realOrResolved(abs));
  if (rel === '' || (!rel.startsWith('..') && !isAbsolute(rel))) return abs;
  throw new Error(`transcripts folder ${abs} is outside ${realProjectsRoot()}`);
}

/** Where his Claude Code session transcripts live. Tests point PALIMPSEST_CLAUDE_PROJECTS at a temp dir and set PALIMPSEST_TEST_PROJECTS=1. */
export function projectsDir(): string {
  return checkedProjectsDir(process.env.PALIMPSEST_CLAUDE_PROJECTS ?? realProjectsRoot());
}

/** Every reading in readings.jsonl taken at or after `sinceMs`, oldest first. Unparseable lines are skipped. */
export function readings(sinceMs: number): UsageReading[] {
  const path = join(paths().usage, 'readings.jsonl');
  if (!existsSync(path)) return [];
  const out: UsageReading[] = [];
  for (const line of readFileSync(path, 'utf8').split('\n')) {
    if (line.trim() === '') continue;
    try {
      const r = mapRecord(JSON.parse(line) as RawRecord);
      if (Number.isFinite(r.at) && r.at >= sinceMs) out.push(r);
    } catch {
      // A torn line from a crash mid-write: skip it.
    }
  }
  return out.sort((a, b) => a.at - b.at);
}

/** Every .jsonl file under `dir` with its mtime. Symlinks (files or folders) are never followed, so the scan stays inside `dir`. */
function transcriptFiles(dir: string): Array<{ path: string; mtimeMs: number; size: number; ino: number }> {
  const root = checkedProjectsDir(dir);
  const out: Array<{ path: string; mtimeMs: number; size: number; ino: number }> = [];
  const walk = (d: string, depth: number): void => {
    if (depth > 8) return;
    let entries;
    try {
      entries = readdirSync(d, { withFileTypes: true });
    } catch {
      return;
    }
    for (const e of entries) {
      const path = join(d, e.name);
      if (e.isSymbolicLink()) continue;
      if (e.isDirectory()) walk(path, depth + 1);
      else if (e.isFile() && e.name.endsWith('.jsonl')) {
        try {
          const st = lstatSync(path);
          out.push({ path, mtimeMs: st.mtimeMs, size: st.size, ino: st.ino });
        } catch {
          // Removed while we looked.
        }
      }
    }
  };
  // The root itself may be a symlink (checked above to resolve inside his projects folder); nothing under it is followed.
  const realRoot = realOrResolved(root);
  try {
    if (!lstatSync(realRoot).isDirectory()) return [];
  } catch {
    return [];
  }
  walk(realRoot, 0);
  return out;
}

interface TranscriptLine {
  type?: string;
  timestamp?: string;
  requestId?: string;
  message?: {
    id?: string;
    model?: string;
    usage?: {
      input_tokens?: number;
      output_tokens?: number;
      cache_read_input_tokens?: number;
      cache_creation_input_tokens?: number;
    };
  };
}

/**
 * His weighted Claude tokens between `fromMs` (exclusive) and `toMs`
 * (inclusive): the `message.usage` of every assistant line in his session
 * transcripts, one per `message.id` plus `requestId` (Claude Code writes a
 * streamed message more than once; the largest count is kept), weighted per
 * `message.model`. City runs never write here (ruling 10), so all of it is his.
 * Files last modified before `fromMs` are skipped unread.
 */
export function transcriptTokens(fromMs: number, toMs: number, dir: string = projectsDir()): { weighted: number; messages: number } {
  const seen = new Map<string, number>();
  const files = transcriptFiles(dir);
  // A transcript that is gone takes its cached lines with it.
  const present = new Set(files.map((f) => f.path));
  const root = realOrResolved(checkedProjectsDir(dir)) + sep;
  for (const path of transcriptCache.keys()) if (path.startsWith(root) && !present.has(path)) transcriptCache.delete(path);
  for (const file of files) {
    if (file.mtimeMs < fromMs) continue;
    for (const e of transcriptEntries(file)) {
      if (!(e.at > fromMs && e.at <= toMs)) continue;
      seen.set(e.key, Math.max(seen.get(e.key) ?? 0, e.w));
    }
  }
  let weighted = 0;
  for (const w of seen.values()) weighted += w;
  return { weighted: Math.round(weighted * 1e6) / 1e6, messages: seen.size };
}

/** One assistant usage line of a transcript: when, which message, its weighted tokens. */
interface TranscriptEntry {
  at: number;
  key: string;
  w: number;
}

/**
 * What each transcript has yielded so far, by path. A file that grew is
 * read only from where the last read stopped (the last full line); one that
 * shrank or was replaced (another inode) is read again from the start. The
 * treasury reads transcripts every few seconds while a run is live, so his
 * whole history is parsed once, not on every read.
 */
const transcriptCache = new Map<string, { ino: number; size: number; mtimeMs: number; offset: number; entries: TranscriptEntry[] }>();

/** Transcripts held in the cache. For tests. */
export function transcriptCacheSize(): number {
  return transcriptCache.size;
}

/** Forgets the transcript cache. For tests. */
export function resetTranscriptCache(): void {
  transcriptCache.clear();
}

function parseTranscriptLine(line: string): TranscriptEntry | null {
  if (!line.includes('"usage"')) return null;
  let row: TranscriptLine;
  try {
    row = JSON.parse(line) as TranscriptLine;
  } catch {
    return null;
  }
  if (row.type !== 'assistant' || !row.message?.usage || !row.timestamp) return null;
  const at = Date.parse(row.timestamp);
  if (!Number.isFinite(at)) return null;
  const u = row.message.usage;
  const w = weightedTokens(
    {
      input: u.input_tokens ?? 0,
      output: u.output_tokens ?? 0,
      cacheRead: u.cache_read_input_tokens ?? 0,
      cacheCreation: u.cache_creation_input_tokens ?? 0,
    },
    row.message.model ?? '',
  );
  return { at, key: `${row.message.id ?? ''}\u0000${row.requestId ?? ''}`, w };
}

function transcriptEntries(file: { path: string; mtimeMs: number; size: number; ino: number }): TranscriptEntry[] {
  let c = transcriptCache.get(file.path);
  if (c && c.ino === file.ino && c.size === file.size && c.mtimeMs === file.mtimeMs) return c.entries;
  if (!c || c.ino !== file.ino || file.size < c.offset) {
    c = { ino: file.ino, size: 0, mtimeMs: 0, offset: 0, entries: [] };
    transcriptCache.set(file.path, c);
  }
  let fd: number;
  try {
    fd = openSync(file.path, fsConstants.O_RDONLY | fsConstants.O_NOFOLLOW);
  } catch {
    return c.entries;
  }
  try {
    const st = fstatSync(fd);
    if (st.ino !== c.ino) return c.entries;
    const length = st.size - c.offset;
    if (length > 0) {
      const buf = Buffer.alloc(length);
      let got = 0;
      while (got < length) {
        const n = readSync(fd, buf, got, length - got, c.offset + got);
        if (n <= 0) break;
        got += n;
      }
      // Only whole lines are consumed; a line still being written waits for the next read.
      const last = buf.lastIndexOf(0x0a, got - 1);
      if (last >= 0) {
        for (const line of buf.subarray(0, last + 1).toString('utf8').split('\n')) {
          const e = parseTranscriptLine(line);
          if (e) c.entries.push(e);
        }
        c.offset += last + 1;
      }
    }
    c.size = file.size;
    c.mtimeMs = file.mtimeMs;
  } catch {
    // Unreadable now: keep what we have.
  } finally {
    closeSync(fd);
  }
  return c.entries;
}

/** True when any transcript under `dir` was written in the last ten minutes: he is using Claude Code now (spec 17). */
export function interactiveActive(now: number = Date.now(), dir: string = projectsDir()): boolean {
  return transcriptFiles(dir).some((f) => now - f.mtimeMs <= INTERACTIVE_MS && f.mtimeMs - now <= INTERACTIVE_MS);
}

/** Weighted tokens the city's own Claude calls spent between `fromMs` (exclusive) and `toMs` (inclusive), from the credits table. */
export function cityWeighted(fromMs: number, toMs: number): number {
  const row = openDb()
    .prepare(
      `SELECT COALESCE(SUM(json_extract(json, '$.weightedTokens')), 0) AS w FROM credits
       WHERE at > ? AND at <= ? AND json_extract(json, '$.model') LIKE 'claude:%'`,
    )
    .get(new Date(fromMs).toISOString(), new Date(toMs).toISOString()) as { w: number };
  return row.w;
}

/** What calibration keeps under the settings key `tokensPerPct`. */
export interface StoredCalibration {
  value: number;
  samples: number;
  /** The `at` of the last reading already counted. */
  through: number;
  /** Sums over same-window pairs, for the weekly ratio. */
  fiveSum: number;
  weekSum: number;
}

const CALIBRATION_KEY = 'tokensPerPct';

/** The stored calibration, or the assumed prior. Cheap: no transcript reading. */
export function storedCalibration(): StoredCalibration {
  const row = openDb().prepare('SELECT json FROM settings WHERE key = ?').get(CALIBRATION_KEY) as { json: string } | undefined;
  const prior: StoredCalibration = { value: DEFAULT_TOKENS_PER_PCT, samples: 0, through: 0, fiveSum: 0, weekSum: 0 };
  if (!row) return prior;
  try {
    const v = JSON.parse(row.json) as Partial<StoredCalibration>;
    return {
      value: typeof v.value === 'number' && v.value > 0 ? v.value : prior.value,
      samples: v.samples ?? 0,
      through: v.through ?? 0,
      fiveSum: v.fiveSum ?? 0,
      weekSum: v.weekSum ?? 0,
    };
  } catch {
    return prior;
  }
}

/** Weekly percentage points per percent of the five-hour window: measured once enough pairs exist, else assumed. */
export function weekPerWindowPct(c: StoredCalibration = storedCalibration()): number {
  if (c.fiveSum >= WEEK_RATIO_MIN_PCT && c.weekSum > 0) return Math.round((c.weekSum / c.fiveSum) * 1e9) / 1e9;
  return DEFAULT_WEEK_PER_WINDOW_PCT;
}

/**
 * Measures weighted tokens per percent of the five-hour window (ruling 2):
 * for each pair of consecutive readings in the same window (equal
 * `resetsAt`) whose percent rose, `observed = (his transcript tokens + the
 * city's tokens between them) / delta`, blended into the estimate with
 * `calibrate()`. Only pairs newer than the last run are counted, and the
 * result is stored under the settings key `tokensPerPct`.
 */
export function calibration(): { tokensPerPct: number; calibrated: boolean; samples: number } {
  const stored = storedCalibration();
  const rs = readings(stored.through);
  let { value, samples, through, fiveSum, weekSum } = stored;
  let changed = false;
  for (let i = 1; i < rs.length; i++) {
    const a = rs[i - 1];
    const b = rs[i];
    if (b.at <= stored.through) continue;
    through = Math.max(through, b.at);
    changed = true;
    if (!a.fiveHour || !b.fiveHour || a.fiveHour.resetsAt !== b.fiveHour.resetsAt) continue;
    const delta = b.fiveHour.usedPercentage - a.fiveHour.usedPercentage;
    if (!(delta > 0)) continue;
    const tokens = transcriptTokens(a.at, b.at).weighted + cityWeighted(a.at, b.at);
    if (tokens > 0) {
      value = calibrate(value, tokens / delta);
      samples += 1;
    }
    if (a.sevenDay && b.sevenDay && a.sevenDay.resetsAt === b.sevenDay.resetsAt) {
      const weekDelta = b.sevenDay.usedPercentage - a.sevenDay.usedPercentage;
      if (weekDelta >= 0) {
        fiveSum += delta;
        weekSum += weekDelta;
      }
    }
  }
  if (rs.length > 0 && rs[rs.length - 1].at > through) {
    through = rs[rs.length - 1].at;
    changed = true;
  }
  if (changed) {
    const next: StoredCalibration = { value, samples, through, fiveSum, weekSum };
    openDb()
      .prepare('INSERT INTO settings (key, json) VALUES (?, ?) ON CONFLICT(key) DO UPDATE SET json = excluded.json')
      .run(CALIBRATION_KEY, JSON.stringify(next));
  }
  return { tokensPerPct: value, calibrated: samples > 0, samples };
}
